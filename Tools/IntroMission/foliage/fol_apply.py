"""Apply a foliage plan (plan_r<N>.json from fol_plan.py) to Ger_IntroMission in the throwaway editor.

    exec(open(FOL + 'fol_apply.py').read()); apply_plan(1)          # clears every FOL_* actor first
    readback(1)   -> Saved/IntroFoliage/readback_r1.json: the instance positions the actors REALLY hold
                     (crushable plants are generated by the crop-field actor itself, so the plan only has outlines)

Small detail: one HierarchicalInstancedStaticMesh actor per mesh per 100 m tile (FOL_Detail_<mesh>_<tx>_<ty>),
no collision, never affects navigation, culled at distance. Folder IntroFoliage/Detail.
Crushable scrub: BP_CrushableScrub_DeadBrush / _DryGrass actors (FOL_Scrub_<n>), outline = plan polygon, no nav area.
Folder IntroFoliage/Scrub.
"""
import json
import math

import unreal

FOL_ROOT = 'D:/UE5Projects/RTS_Survival/Saved/IntroFoliage/'
SCRUB = '/Game/RTS_Survival/Blueprints/Environment/CrushableInstancedActor/DryScrub/BP_CrushableScrub_'
TILE = 10000.0
CULL = (11000.0, 16000.0)
SHADOW_MESHES = ('SM_GF_DryTuft_A', 'SM_GF_DryTuft_B')


def _eas():
    return unreal.get_editor_subsystem(unreal.EditorActorSubsystem)


def _world():
    return unreal.get_editor_subsystem(unreal.UnrealEditorSubsystem).get_editor_world()


def clear_fol(prefix='FOL_'):
    n = 0
    for a in _eas().get_all_level_actors():
        if a.get_actor_label().startswith(prefix):
            _eas().destroy_actor(a)
            n += 1
    print('cleared', n, prefix)


def _hism_actor(label, folder, mesh, transforms, shadow, material=None):
    actor = _eas().spawn_actor_from_class(unreal.Actor, unreal.Vector(0.0, 0.0, 0.0))
    actor.set_actor_label(label)
    actor.set_folder_path(folder)
    sds = unreal.get_engine_subsystem(unreal.SubobjectDataSubsystem)
    root = sds.k2_gather_subobject_data_for_instance(actor)[0]
    handle, _ = sds.add_new_subobject(unreal.AddNewSubobjectParams(
        parent_handle=root, new_class=unreal.HierarchicalInstancedStaticMeshComponent))
    comp = unreal.SubobjectDataBlueprintFunctionLibrary.get_object(unreal.SubobjectDataBlueprintFunctionLibrary.get_data(handle))
    comp.set_static_mesh(mesh)
    comp.set_mobility(unreal.ComponentMobility.STATIC)
    comp.set_collision_enabled(unreal.CollisionEnabled.NO_COLLISION)
    comp.set_editor_property('can_ever_affect_navigation', False)
    comp.set_editor_property('receives_decals', False)      # cliff stone decals must not paint the grass cards
    comp.set_editor_property('cast_shadow', shadow)
    if material is not None:
        for k in range(comp.get_num_materials()):
            comp.set_material(k, material)
    comp.set_editor_property('instance_start_cull_distance', int(CULL[0]))
    comp.set_editor_property('instance_end_cull_distance', int(CULL[1]))
    comp.add_instances(transforms, False, True)
    return actor


def apply_detail(plan):
    total = 0
    mats = plan.get('materials', {})
    for key, items in plan['detail'].items():
        mesh_path = key.split('#')[0]          # 'mesh#pit': same mesh, own material (round 4)
        mesh = unreal.load_asset(mesh_path)
        mat = unreal.load_asset(mats[key]) if mats.get(key) else None
        name = key.split('/')[-1].replace('#', '_')
        tiles = {}
        for it in items:
            tiles.setdefault((int(math.floor(it[0] / TILE)), int(math.floor(it[1] / TILE))), []).append(it)
        for (tx, ty), its in sorted(tiles.items()):
            transforms = [unreal.Transform(unreal.Vector(x, y, z), unreal.Rotator(roll, pitch, yaw), unreal.Vector(s, s, s))
                          for x, y, z, yaw, s, pitch, roll in its]
            _hism_actor('FOL_Detail_%s_%d_%d' % (name.replace('SM_', ''), tx, ty), 'IntroFoliage/Detail/' + name,
                        mesh, transforms, mesh_path.split('/')[-1] in SHADOW_MESHES, mat)
            total += len(its)
    print('detail instances', total)


def _ground(x, y):
    hit = unreal.SystemLibrary.line_trace_single(_world(), unreal.Vector(x, y, 20000.0), unreal.Vector(x, y, -20000.0),
                                                 unreal.TraceTypeQuery.TRACE_TYPE_QUERY1, False, [],
                                                 unreal.DrawDebugTrace.NONE, True)
    return hit.to_tuple()[4].z if hit else 150.0


def _set_points(spline, pts):
    spline.clear_spline_points(False)
    for p in pts:
        spline.add_spline_point(p, unreal.SplineCoordinateSpace.LOCAL, False)
    for i in range(len(pts)):
        spline.set_spline_point_type(i, unreal.SplinePointType.LINEAR, False)
    spline.set_closed_loop(True, False)
    spline.update_spline()
    spline.set_editor_property('spline_has_been_edited', True)


def apply_patches(plan):
    classes = {}
    for k, p in enumerate(plan['patches']):
        bp = p['bp']
        if bp not in classes:
            classes[bp] = unreal.load_asset(SCRUB + bp).generated_class()
        cx, cy = p['centre']
        origin = unreal.Vector(cx, cy, _ground(cx, cy))
        a = _eas().spawn_actor_from_class(classes[bp], origin, unreal.Rotator(0.0, 0.0, 0.0))
        a.set_actor_label('FOL_Scrub_%s_%02d' % (bp, k))
        a.set_folder_path('IntroFoliage/Scrub')
        _set_points(a.get_editor_property('field_outline'),
                    [unreal.Vector(x - cx, y - cy, 0.0) for x, y in p['poly']])
        lay = a.get_editor_property('layout')
        lay.set_editor_property('random_seed', p['seed'])
        if p.get('layout'):                        # round 4: per-patch spacing / scale (6-10 plants per patch)
            L = p['layout']
            lay.set_editor_property('row_spacing', float(L['spacing']))
            lay.set_editor_property('plant_spacing', float(L['spacing']))
            lay.set_editor_property('min_scale', float(L['smin']))
            lay.set_editor_property('max_scale', float(L['smax']))
        a.set_editor_property('layout', lay)       # setting a property reruns the construction script
    print('patches', len(plan['patches']))


def apply_plan(round_no):
    with open(FOL_ROOT + 'plan_r%d.json' % round_no) as h:
        plan = json.load(h)
    clear_fol('FOL_Detail_')
    clear_fol('FOL_Scrub_')
    apply_detail(plan)
    apply_patches(plan)


def readback(round_no):
    """Every instance the FOL_ actors hold, in world space: {label: {'class', 'mesh': [[x, y, z, scale]...]}}."""
    out = {}
    for a in _eas().get_all_level_actors():
        label = a.get_actor_label()
        if not label.startswith(('FOL_', 'POIW_', 'POIE_')):
            continue
        rot = a.get_actor_rotation()
        sc = a.get_actor_scale3d()
        entry = {'class': a.get_class().get_name(),
                 'loc': [round(v) for v in (a.get_actor_location().x, a.get_actor_location().y, a.get_actor_location().z)],
                 'rot_pitch_yaw_roll': [round(rot.pitch, 1), round(rot.yaw, 1), round(rot.roll, 1)],
                 'scale': [round(sc.x, 3), round(sc.y, 3), round(sc.z, 3)], 'inst': {}}
        smc = a.get_component_by_class(unreal.StaticMeshComponent)
        if smc and not isinstance(smc, unreal.InstancedStaticMeshComponent) and smc.get_editor_property('static_mesh'):
            entry['mesh'] = smc.get_editor_property('static_mesh').get_path_name().split('.')[0]
        for c in a.get_components_by_class(unreal.InstancedStaticMeshComponent):
            mesh = c.get_editor_property('static_mesh')
            pts = []
            for k in range(c.get_instance_count()):
                t = c.get_instance_transform(k, True)
                pts.append([round(t.translation.x), round(t.translation.y), round(t.translation.z), round(t.scale3d.x, 2)])
            if pts:
                entry['inst'].setdefault(mesh.get_name() if mesh else '?', []).extend(pts)
        out[label] = entry
    with open(FOL_ROOT + 'readback_r%d.json' % round_no, 'w') as h:
        json.dump(out, h)
    n = sum(len(v) for e in out.values() for v in e['inst'].values())
    print('readback actors', len(out), 'instances', n)
    return out
