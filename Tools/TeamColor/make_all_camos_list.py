"""Writes the capture list for the all-camos review: one vehicle per distinct camo, in Default, Red and Blue.

Usage: python make_all_camos_list.py <survey json> <output list>
Variants that only add a glow or reuse another vehicle's paint are left out; see make_fleet_capture_list.py for the format.
"""
import json
import sys

from make_fleet_capture_list import COLORS

ALL_CAMOS = [
    # Tanks and tank destroyers.
    "Ger_Vehicle_PanzerII_F", "Ger_Vehicle_PanzerII_Luchs", "Ger_Vehicle_PanzerII_Luchs_FlakLuchs",
    "Ger_Vehicle_PanzerII_Luchs_SpacedArmor", "Ger_Vehicle_Panzer38T", "Ger_Vehicle_Panzer38T_R_IncendiarySalvo",
    "Ger_Vehicle_PanzerIII_M", "Ger_Vehicle_PanzerIII_Flamm", "Ger_Vehicle_PanzerIV_G", "Ger_Vehicle_PanzerIV_H",
    "Ger_Vehicle_PanzerIV_H_Ostwind", "Ger_Vehicle_PantherD", "Ger_Vehicle_PantherG", "Ger_Vehicle_PantherII",
    "Ger_Vehicle_PanzerV_III", "Ger_Vehicle_TigerE", "Ger_Vehicle_TigerH1", "Ger_Vehicle_TigerII", "Ger_Vehicle_E25",
    "Ger_Vehicle_E50", "Ger_Vehicle_E75", "Ger_Vehicle_E100", "Ger_Vehicle_Maus", "Ger_Vehicle_Hetzer",
    "Ger_Vehicle_Hetzer_Flame", "Ger_Vehicle_Hetzer_Mortar", "Ger_Vehicle_PanzerJager1", "Ger_Vehicle_Marder",
    "Ger_Vehicle_StugIII", "Ger_Vehicle_JagdPanzerIV70", "Ger_Vehicle_JagdPanther", "Ger_Vehicle_JagdTiger",
    "Ger_Vehicle_Brummbar", "Ger_Vehicle_SturmTiger", "Ger_Vehicle_Wespe", "Ger_Vehicle_Pz1_15CM",
    "Ger_Vehicle_SDKFZ-140", "Ger_Vehicle_SDKFZ-140_AA", "Ger_Harvester_Panzer1",
    # Armoured cars, half-tracks and trucks.
    "Ger_ArmoredCar_Keubel", "Ger_ArmoredCar_Puma", "Ger_ArmoredCar_Puma_DualBarrel",
    "Ger_ArmoredCar_Puma_RadixiteSniper", "Ger_ArmoredCar_Sdkfz250", "Ger_ArmoredCar_Sdkfz250_37",
    "Ger_ArmoredCar_Sdkfz250_ArmouredAmbulance", "Ger_ArmoredCar_251_Transport", "Ger_ArmoredCar_251_AmmoCarrier",
    "Ger_ArmoredCar_Sdkfz-251_75mm", "Ger_ArmoredCar_Sdkfz_231", "Ger_ArmoredCar_Sdkfz_234_3",
    "Ger_Vehicle_Sdkfz7Flak", "Ger_Refinery_Truck", "Ger_Forge_Truck", "Ger_HQ_Truck", "Ger_MechanizedDepot_Truck",
]
REVIEW_COLORS = ["Default", "Red", "Blue"]


def main():
    with open(sys.argv[1], encoding="utf-8") as handle:
        by_name = {path.rsplit("/", 1)[-1]: path for path in json.load(handle)["units"]}
    # Default comes first: the shaders are already compiled from earlier runs, so no warm-up pictures.
    lines = ["# All German camos for review, generated by make_all_camos_list.py"]
    for name in ALL_CAMOS:
        if name not in by_name:
            print(f"missing {name}")
            continue
        for color in REVIEW_COLORS:
            entry = f"{name}_{color}={by_name[name]}.{name}_C"
            if COLORS[color]:
                entry += f"|TeamColor={COLORS[color]},1"
            lines.append(entry)
    with open(sys.argv[2], "w", encoding="utf-8") as handle:
        handle.write("\n".join(lines) + "\n")
    print(f"{len(lines) - 1} entries -> {sys.argv[2]}")


if __name__ == "__main__":
    main()
