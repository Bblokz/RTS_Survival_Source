"""Writes a capture list (run_team_color_capture.sh) for a cross-section of the German fleet with the real materials.

Usage: python make_fleet_capture_list.py <survey json> <output list> [--colors Default,Red,Blue,Green,Yellow]
Entry names are <Unit>_<Color>; Default has no team colour (alpha 0) and must look exactly like the game today.
"""
import argparse
import json

FLEET = ["Ger_Vehicle_PanzerIII_M", "Ger_Vehicle_PanzerIV_H", "Ger_Vehicle_Panzer38T", "Ger_Vehicle_Hetzer",
         "Ger_Vehicle_TigerH1", "Ger_Vehicle_TigerE", "Ger_Vehicle_TigerII", "Ger_Vehicle_PantherD",
         "Ger_Vehicle_PantherG", "Ger_Vehicle_PantherII", "Ger_Vehicle_JagdPanther", "Ger_Vehicle_E50",
         "Ger_Vehicle_Maus", "Ger_ArmoredCar_Puma", "Ger_ArmoredCar_251_Transport", "Ger_Vehicle_Brummbar",
         "Ger_ArmoredCar_Keubel", "Ger_Refinery_Truck", "Ger_Vehicle_Sdkfz7Flak"]
# Linear team colours, alpha 1 = full team colour.
COLORS = {"Default": None, "Red": "0.8,0.02,0.02", "Blue": "0.02,0.1,0.85", "Green": "0.05,0.5,0.03",
          "Yellow": "0.9,0.7,0.02"}


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("survey")
    parser.add_argument("output")
    parser.add_argument("--colors", default=",".join(COLORS))
    arguments = parser.parse_args()
    with open(arguments.survey, encoding="utf-8") as handle:
        units = json.load(handle)["units"]
    by_name = {path.rsplit("/", 1)[-1]: path for path in units}
    lines = ["# German fleet team colour capture, generated by make_fleet_capture_list.py",
             # The first spawn of a unit pictures shaders that may still compile; warm every unit up once.
             *[f"Warmup_{name}={by_name[name]}.{name}_C" for name in FLEET if name in by_name]]
    for name in FLEET:
        if name not in by_name:
            print(f"missing {name}")
            continue
        for color in arguments.colors.split(","):
            entry = f"{name}_{color}={by_name[name]}.{name}_C"
            if COLORS[color]:
                entry += f"|TeamColor={COLORS[color]},1"
            lines.append(entry)
    with open(arguments.output, "w", encoding="utf-8") as handle:
        handle.write("\n".join(lines) + "\n")
    print(f"{len(lines) - 1} entries -> {arguments.output}")


if __name__ == "__main__":
    main()
